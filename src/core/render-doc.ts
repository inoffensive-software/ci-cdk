import type { Doc } from "./doc.js";
import { fail } from "./errors.js";
import { yamlSerializer, type RenderOptions } from "./serialize.js";

export type { RenderOptions } from "./serialize.js";

/** The one permitted comment, with no timestamp and no version, so regenerating never churns. */
export const DEFAULT_HEADER = "Generated by @inoffensive/ci-cdk. Do not edit.";

const BLOCK_SCALAR = /[|>][+-]?\d*$/u;
const DOCUMENT_MARKER = /^---(?:\s|$)/u;
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/u;
const TAG_BODY = /^(?:[A-Za-z0-9\-;/?:@&=+$_.~*'()#]|%[0-9A-Fa-f]{2})+$/u;

/**
 * A local tag (`!name`) or a secondary one (`!!name`). A named handle (`!e!name`) is rejected: it
 * needs a `%TAG` directive, which this emitter never writes.
 */
const isValidTag = (tag: string): boolean => {
  if (!tag.startsWith("!")) {
    return false;
  }

  const body = tag.startsWith("!!") ? tag.slice(2) : tag.slice(1);

  return body.length > 0 && !body.includes("!") && TAG_BODY.test(body);
};

/** Root is `$`; `.name` for a plain identifier, `["name"]` otherwise. */
const entryPath = (path: string, key: string): string =>
  IDENTIFIER.test(key) ? `${path}.${key}` : `${path}[${JSON.stringify(key)}]`;

const assertValidTag = (tag: string | undefined, path: string): void => {
  if (tag === undefined) {
    return;
  }

  if (!isValidTag(tag)) {
    fail({
      path,
      message: `${JSON.stringify(tag)} is not a valid YAML tag`,
      hint: "a tag is '!' followed by tag characters, with no quotes, brackets or whitespace",
    });
  }
};

const assertRenderable = (doc: Doc, path: string): void => {
  assertValidTag(doc.tag, path);

  switch (doc.kind) {
    case "scalar":
      return;

    case "seq":
      for (const [index, item] of doc.items.entries()) {
        assertRenderable(item, `${path}[${index}]`);
      }

      return;

    case "map": {
      const seen = new Set<string>();

      for (const entry of doc.entries) {
        const pathToEntry = entryPath(path, entry.key);

        if (seen.has(entry.key)) {
          fail({ path: pathToEntry, message: `duplicate key "${entry.key}"` });
        }

        seen.add(entry.key);
        assertRenderable(entry.value, pathToEntry);
      }

      return;
    }

    default:
      fail({
        path,
        message: "the serializer received a node whose kind is not map, seq or scalar",
        hint: "build nodes with the core constructors",
      });
  }
};

interface Scanned {
  readonly lines: string[];
  /** `true` where the line is the body of a literal or folded block scalar. */
  readonly inBlock: boolean[];
  /** `true` when the document ends inside a block scalar, so its trailing lines are content. */
  readonly openBlock: boolean;
}

/**
 * Splits the serializer's output and marks block-scalar body lines. Trailing whitespace is content
 * inside a block scalar, so it is only stripped outside one.
 */
const scan = (text: string): Scanned => {
  const source = text.replaceAll("\r\n", "\n").split("\n");
  const lines: string[] = [];
  const inBlock: boolean[] = [];
  let blockIndent: number | null = null;

  for (const line of source) {
    const indent = line.length - line.trimStart().length;
    const inside = blockIndent !== null && (line.trim() === "" || indent > blockIndent);

    if (!inside) {
      blockIndent = null;
    }

    lines.push(inside ? line : line.replaceAll(/\s+$/gu, ""));
    inBlock.push(inside);

    if (!inside && BLOCK_SCALAR.test(line.trimEnd())) {
      blockIndent = indent;
    }
  }

  return { lines, inBlock, openBlock: blockIndent !== null };
};

const failIfBlankLine = (lines: readonly string[], inBlock: readonly boolean[]): void => {
  for (const [index, line] of lines.entries()) {
    // A blank line inside a block scalar is content; anywhere else it breaks the contract.
    if (line.trim() === "" && inBlock[index] !== true) {
      fail({ path: "$", message: "the serializer emitted a blank line" });
    }
  }
};

const normalise = (text: string): string => {
  const { lines, inBlock, openBlock } = scan(text);

  if (!openBlock) {
    while (lines.at(-1) === "") {
      lines.pop();
      inBlock.pop();
    }
  }

  if (lines.some((line) => DOCUMENT_MARKER.test(line))) {
    fail({ path: "$", message: "the serializer emitted a document marker" });
  }

  failIfBlankLine(lines, inBlock);

  const body = lines.join("\n");

  if (openBlock) {
    return body.endsWith("\n") ? body : `${body}\n`;
  }

  return `${body}\n`;
};

/**
 * `Doc` in, text out. Provider-blind: the YAML serializer is selected here, not passed in.
 */
export const renderDoc = (doc: Doc, options?: RenderOptions): string => {
  const header = options?.header ?? DEFAULT_HEADER;

  if (/[\r\n\u2028\u2029]/u.test(header)) {
    fail({
      path: "$",
      message: "the header must be a single line",
      hint: 'pass { header: "" } to omit the header',
    });
  }

  assertRenderable(doc, "$");

  return normalise(yamlSerializer.render(doc, { header }));
};
