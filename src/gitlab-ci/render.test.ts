import { describe, expect, it } from "vitest";
import { parse } from "yaml";

import { type Pipeline, job, pipeline, render } from "./index.js";

const twoStages = (): Pipeline =>
  pipeline({
    stages: ["build", "test"],
    jobs: [
      job({ name: "build", stage: "build", script: ["npm ci", "npm run build"] }),
      job({ name: "test", script: "npm test" }),
    ],
  });

const oneJob = (name: string, script: string): Pipeline =>
  pipeline({ jobs: [job({ name, script })] });

describe("render", () => {
  it("pins a two-stage pipeline with two jobs", async () => {
    await expect(render(twoStages())).toMatchFileSnapshot("__snapshots__/two-jobs.yml");
  });

  it("emits stages first, then one entry per job in array order", () => {
    const text = render(twoStages(), { header: "" });

    expect(text).toBe(
      "stages:\n" +
        "  - build\n" +
        "  - test\n" +
        "build:\n" +
        "  stage: build\n" +
        "  script:\n" +
        "    - npm ci\n" +
        "    - npm run build\n" +
        "test:\n" +
        "  script: npm test\n",
    );
  });

  it("keys jobs by name in array order, not alphabetically", () => {
    const text = render(
      pipeline({
        jobs: [job({ name: "zulu", script: "true" }), job({ name: "alpha", script: "true" })],
      }),
      { header: "" },
    );

    expect(text.indexOf("zulu:")).toBeLessThan(text.indexOf("alpha:"));
  });

  it("never writes the job name inside the job body", () => {
    const text = render(twoStages(), { header: "" });
    const parsed = parse(text);

    expect(text).not.toContain("name:");
    expect(parsed).toStrictEqual({
      stages: ["build", "test"],
      build: { stage: "build", script: ["npm ci", "npm run build"] },
      test: { script: "npm test" },
    });
  });
});

describe("options", () => {
  it("suppresses the header on request and keeps the default header unchanged", () => {
    const headed = render(twoStages());

    expect(render(twoStages(), { header: "" }).startsWith("stages:\n")).toBe(true);
    expect(headed.startsWith("# Generated by @inoffensive/ci-cdk. Do not edit.\nstages:\n")).toBe(
      true,
    );
  });

  it("is deterministic across two renders of the same struct", () => {
    expect(render(twoStages())).toBe(render(twoStages()));
  });
});

describe("stages", () => {
  it("emits an empty stages array as []", () => {
    const text = render(pipeline({ stages: [], jobs: [] }), { header: "" });

    expect(text).toBe("stages: []\n");
    expect(parse(text)).toStrictEqual({ stages: [] });
  });

  it("omits the stage key when the job does not set one", () => {
    const text = render(oneJob("lint", "npm run lint"), { header: "" });

    expect(text).toBe("lint:\n  script: npm run lint\n");
    expect(parse(text)).toStrictEqual({ lint: { script: "npm run lint" } });
  });

  it("accepts .pre and .post whether or not stages declares them", () => {
    const declared = pipeline({
      stages: ["build", "deploy"],
      jobs: [
        job({ name: "prepare", stage: ".pre", script: "true" }),
        job({ name: "cleanup", stage: ".post", script: "true" }),
      ],
    });

    const bare = pipeline({
      jobs: [job({ name: "prepare", stage: ".pre", script: "true" })],
    });

    expect(render(declared, { header: "" })).toContain("  stage: .pre\n");
    expect(render(bare, { header: "" })).toContain("  stage: .pre\n");
  });

  it("accepts a job stage drawn from GitLab's default stages", () => {
    expect(() =>
      render(pipeline({ jobs: [job({ name: "build", stage: "build", script: "true" })] })),
    ).not.toThrow();
  });
});

describe("script", () => {
  it("omits the key entirely when the job declares no script", () => {
    const text = render(pipeline({ jobs: [job({ name: "markdownlint", needs: [] })] }), {
      header: "",
    });

    expect(parse(text)).toStrictEqual({ markdownlint: { needs: [] } });
    expect(text).not.toContain("script");
  });

  it("round-trips a single string", () => {
    const text = render(oneJob("build", "npm test"), { header: "" });

    expect(parse(text)).toStrictEqual({ build: { script: "npm test" } });
  });

  it("round-trips an ordered string array", () => {
    const script = ["npm ci", "npm run build"] as const;
    const text = render(pipeline({ jobs: [job({ name: "build", script })] }), { header: "" });

    expect(parse(text)).toStrictEqual({ build: { script: ["npm ci", "npm run build"] } });
  });

  it("keeps a multi-line command as one string", () => {
    const script = "echo one\necho two";
    const text = render(oneJob("build", script), { header: "" });

    expect(parse(text)).toStrictEqual({ build: { script } });
  });

  it.each([
    ["colon", "echo done: now"],
    ["comment", "echo done # note"],
    ["yaml 1.1 boolean", "yes"],
    ["non-canonical number", "1.10"],
    ["leading dash", "- not a sequence item"],
  ])("keeps a script that needs quoting as the same string (%s)", (_label, script) => {
    const text = render(oneJob("build", script), { header: "" });

    expect(parse(text)).toStrictEqual({ build: { script } });
  });
});

describe("multi-line scripts", () => {
  const install = "if [ -f pnpm-lock.yaml ]; then\n  pnpm install --frozen-lockfile\nfi";

  // Longer than the fold threshold, so a double-quoted scalar would otherwise wrap across physical
  // lines and leave a blank line the format contract forbids.
  it("keeps a realistic command as one string", () => {
    const text = render(oneJob("build", install), { header: "" });

    expect(text.split("\n")).toHaveLength(3);
    expect(parse(text)).toStrictEqual({ build: { script: install } });
  });

  it("keeps a realistic command inside a script array", () => {
    const script = ["npm ci", install] as const;
    const text = render(pipeline({ jobs: [job({ name: "build", script })] }), { header: "" });

    expect(text.split("\n")).toHaveLength(5);
    expect(parse(text)).toStrictEqual({ build: { script: ["npm ci", install] } });
  });
});

describe("builders", () => {
  it("returns their input unchanged", () => {
    const builtJob = job({ name: "build", script: "npm test" });
    const builtPipeline = pipeline({ jobs: [builtJob] });

    expect(job(builtJob)).toBe(builtJob);
    expect(pipeline(builtPipeline)).toBe(builtPipeline);
  });
});
